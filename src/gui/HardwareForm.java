    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String searchID = txtSearchHardware.getText().trim();

        if(searchID.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please enter a Hardware ID.");
            return;
        }//end if
        sortHardwareByID();

        Hardware result = binarySearchHardware(searchID);
        
        if(result == null){
            JOptionPane.showMessageDialog(this, "Hardware ID " + searchID +
                    " was not found.");
            return;
        }//end if

        txtHardwareID.setText(result.getAssetId());
        txtHardwareName.setText(result.getAssetName());
        cmbType.setSelectedItem(result.getHardwareType());
        cmbStatus.setSelectedItem(result.getStatus());
        txtMonthlyCost.setText(Double.toString(result.getMonthlyCost()));

        //end search button
    }//GEN-LAST:event_btnSearchActionPerformed

