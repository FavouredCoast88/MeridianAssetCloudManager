    private Hardware binarySearchHardware(String targetID){

        int left = 0;
        int right = hardwareList.size() - 1;

        while(left <= right){

            int middle = (left + right) / 2;

            String middleID = hardwareList.get(middle).getAssetId();
            
            int comparison = middleID.compareToIgnoreCase(targetID);

            if(comparison == 0){
                return hardwareList.get(middle);
            }//end if

            if(comparison < 0){
                left = middle + 1;
            }else{
                right = middle - 1;
            }//end else
        }//end while
        return null;
    }//end binarySearchHardware method
    private void sortHardwareByID(){
        hardwareList.sort((h1, h2) -> h1.getAssetId().compareToIgnoreCase
        (h2.getAssetId()));
    }//end sortHardwareByID method

