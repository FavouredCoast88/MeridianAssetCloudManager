    private void setupTable(){
        DefaultTableModel model = new DefaultTableModel();
        
        model.addColumn("Hardware ID");
        model.addColumn("Name");
        model.addColumn("Type");
        model.addColumn("Status");
        model.addColumn("Monthly Cost(R)");
        
        tblHardware.setModel(model);
    }//end setupTable
    
    private void refreshTable(){
        DefaultTableModel model = (DefaultTableModel) tblHardware.getModel();
        model.setRowCount(0);
        
        for(Hardware hardware : hardwareList){
            model.addRow(new Object[]{
                hardware.getAssetId(),hardware.getAssetName(),hardware.getHardwareType(),
                hardware.getStatus(),hardware.getMonthlyCost()
            });
        }//end for
    }//end refreshTable method
    
    private void clearFields(){
        txtHardwareID.setText("");
        txtHardwareName.setText("");
        txtMonthlyCost.setText("");
        cmbType.setSelectedIndex(0);
        cmbStatus.setSelectedIndex(0);
        txtHardwareID.requestFocus();

    }//end clearFields
