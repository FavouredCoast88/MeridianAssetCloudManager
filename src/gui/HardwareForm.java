    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int selectedRow = tblHardware.getSelectedRow();

        if(selectedRow == -1){
            javax.swing.JOptionPane.showMessageDialog(this, "Please select hardware to delete.");
            return;
        }//end if
       
        Hardware hardwareToDelete = hardwareList.get(selectedRow);
        LoggerUtil.log("DELETE HARDWARE", username);
  
        int choice = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete "
                + hardwareToDelete.getAssetName() + "?", "Confirm Delete",
                javax.swing.JOptionPane.YES_NO_OPTION);
        if(choice != javax.swing.JOptionPane.YES_OPTION){
           return;
        }//end if

        // Save the deleted object for Undo
        deletedHardware.push(hardwareToDelete);
        try{
            applicationState.setDeletedHardware(deletedHardware);
            Serializer.saveState(applicationState);
        }catch(IOException e){
            JOptionPane.showMessageDialog(this, "Could not save application state.");
        }//end catch

        // Remove it from the LinkedList
        hardwareList.remove(selectedRow);

        refreshTable();
            new FileWorker("SAVE_HARDWARE",null,hardwareList,null,()-> SwingUtilities.invokeLater(()->{
                progressBar.setVisible(true);
                progressBar.setIndeterminate(true);
                progressBar.setString("Saving...");
            }),()-> SwingUtilities.invokeLater(()->{
                progressBar.setIndeterminate(false);
                progressBar.setValue(100);
                progressBar.setString("Saved");
                javax.swing.Timer timer = new javax.swing.Timer(1500, e -> progressBar.setVisible(false));
                timer.setRepeats(false);
                timer.start();
            })).execute();
        clearFields();
        javax.swing.JOptionPane.showMessageDialog(this, "Hardware deleted. You can use Undo Delete to restore it.");   
     //end delete button
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnUndoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUndoActionPerformed
        if(deletedHardware.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "There is nothing to undo.");
            return;
        }//end if

        Hardware restoredHardware = deletedHardware.pop();
        try{
            applicationState.setDeletedHardware(deletedHardware);
            Serializer.saveState(applicationState);
        }catch(IOException e){
            JOptionPane.showMessageDialog(this, "Could not save application state.");
        }//end catch
         
        LoggerUtil.log("UNDO DELETE HARDWARE",username);
        hardwareList.add(restoredHardware);
        refreshTable();
        new FileWorker("SAVE_HARDWARE",null,hardwareList,null,()-> SwingUtilities.invokeLater(()->{
            progressBar.setVisible(true);
            progressBar.setIndeterminate(true);
            progressBar.setString("Saving...");
        }),()-> SwingUtilities.invokeLater(()->{
            progressBar.setIndeterminate(false);
            progressBar.setValue(100);
            progressBar.setString("Saved");
            javax.swing.Timer timer = new javax.swing.Timer(1500, e -> progressBar.setVisible(false));
            timer.setRepeats(false);
            timer.start();
        })).execute(); 
        javax.swing.JOptionPane.showMessageDialog(this, "Hardware restored successfully.");
     //end undoDelete button
    }//GEN-LAST:event_btnUndoActionPerformed

