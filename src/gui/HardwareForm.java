    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String id = txtHardwareID.getText().trim();
        String name = txtHardwareName.getText().trim();
        String type = cmbType.getSelectedItem().toString();
        String status = cmbStatus.getSelectedItem().toString();
        String costText = txtMonthlyCost.getText().trim();

        if(id.isEmpty() || name.isEmpty() || costText.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Please complete all fields.");
            return;
        }//end if

        double monthlyCost;

        try{
            monthlyCost = Double.parseDouble(costText);
             
            if(monthlyCost < 0){
                javax.swing.JOptionPane.showMessageDialog(this, "Monthly cost cannot be negative.");
                return;
            }//end if
        }catch(NumberFormatException e){
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid monthly cost.");
            return;
        }//end catch

        // Check for duplicate Hardware IDs
        for(Hardware hardware : hardwareList){

            if(hardware.getAssetId().equalsIgnoreCase(id)){
                javax.swing.JOptionPane.showMessageDialog(this, "Hardware ID already exists.");
                return;
            }//end if
        }//end for

        Hardware hardware = new Hardware(id, name, type, status, monthlyCost);
        hardwareList.add(hardware);
        LoggerUtil.log("ADD HARDWARE", username);
         
        new FileWorker("SAVE_HARDWARE",null,hardwareList,null,()-> SwingUtilities.invokeLater(()->{
            progressBar.setVisible(true);
            progressBar.setIndeterminate(true);
            progressBar.setString("Saving...");
        }),()-> SwingUtilities.invokeLater(()->{
            progressBar.setIndeterminate(false);
            progressBar.setValue(100);
            progressBar.setString("Saved");
            javax.swing.Timer timer = new javax.swing.Timer(1500, e -> progressBar.setVisible(false));
            timer.setRepeats(false);
            timer.start();
        })).execute(); 
        refreshTable();
        clearFields();
     //end add button
    }//GEN-LAST:event_btnAddActionPerformed

