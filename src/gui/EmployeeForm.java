    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String id = txtEmployeeID.getText().trim();
        String name = txtEmployeeName.getText().trim();
        String department = cmbDepartment.getSelectedItem().toString();
        
        if(id.isEmpty() || name.isEmpty()){
            JOptionPane.showMessageDialog(this,"Please complete all fields.");
            return;
        }//end if
        for(Employee employee : employees){
            if(employee.getEmployeeId().equalsIgnoreCase(id)){
                JOptionPane.showMessageDialog(this, "Employee ID already exists.");
                return;
            }//end if
        }//end for
    
        Employee employee = new Employee(id, name, department);
        employees.add(employee);
        LoggerUtil.log("ADD EMPLOYEE", username);
        new FileWorker("SAVE_EMPLOYEES",employees,null,null,
                    ()-> SwingUtilities.invokeLater(()->{
                        progressBar.setVisible(true);
                        progressBar.setIndeterminate(true);
                        progressBar.setString("Saving...");
                    }),
                    ()-> SwingUtilities.invokeLater(()->{
                        progressBar.setIndeterminate(false);
                        progressBar.setValue(100);
                        progressBar.setString("Saved");
                        javax.swing.Timer timer = new javax.swing.Timer(1500, 
                                e -> progressBar.setVisible(false));
                        timer.setRepeats(false);
                        timer.start();
                    })).execute();
        refreshTable();
        clearFields();
     //end add button
    }//GEN-LAST:event_btnAddActionPerformed

