    private void setupTable(){
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
        model.addColumn("Employee ID");
        model.addColumn("Name");
        model.addColumn("Department");
        tblEmployees.setModel(model);    
    }//end setupTable method
    
    private void refreshTable(){
        DefaultTableModel model = (DefaultTableModel) tblEmployees.getModel();
        model.setRowCount(0);
        
        for(Employee employee : employees){
            model.addRow(new Object[]{
                employee.getEmployeeId(),
                employee.getName(),
                employee.getDepartment()});
        }//end for 
    }//end refreshTable method
    
    private void bubbleSortEmployeesByName() {
        for (int i = 0; i < employees.size() - 1; i++) {
            for (int j = 0; j < employees.size() - 1 - i; j++) {

                String name1 = employees.get(j).getName();
                String name2 = employees.get(j + 1).getName();

                if (name1.compareToIgnoreCase(name2) > 0) {
                    Employee temp = employees.get(j);
                    employees.set(j, employees.get(j + 1));
                    employees.set(j + 1, temp);
                }//end if
            }//end for
        }//end for
    }//end bubbleSortEmployeesByName method
    
