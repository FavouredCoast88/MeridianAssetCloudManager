    private void updateDashboardStats(){

        try{
            applicationState = Serializer.loadState();
            int pendingDeployments = applicationState.getDeploymentQueue().size();
            lblPendingDeployments.setText("Pending Deployments: " + pendingDeployments);
        }catch(IOException | ClassNotFoundException e){
           lblPendingDeployments.setText("Pending Deployments: 0");
        }//end catch
    }//end updateDashboardStats method

