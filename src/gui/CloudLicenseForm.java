    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        int selectedRow = tblLicenses.getSelectedRow();
        
        if(selectedRow == -1){
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a license to update.");
            return;
        }//end if
        String id = txtLicenseID.getText().trim();
        String name = txtLicenseName.getText().trim();
        String countText = txtLicenseCount.getText().trim();
        String costText = txtMonthlyCost.getText().trim();
        
        if(id.isEmpty()||name.isEmpty()||countText.isEmpty()||costText.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please complete all fields!");
            return;
        }//end if
        
        int licenseCount;
        double monthlyCost;
        
        try{
            licenseCount = Integer.parseInt(countText);
            monthlyCost = Double.parseDouble(costText);
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Please enter valid numeric values.");
            return;
        }//end catch

        if(licenseCount < 0||monthlyCost < 0){
           JOptionPane.showMessageDialog(this, "Values cannot be negative.");
           return;   
        }//end if
        CloudLicense license = licenses.get(selectedRow);
        license.setAssetId(id);
        license.setAssetName(name);
        license.setLicenseCount(licenseCount);
        license.setMonthlyCost(monthlyCost);
        LoggerUtil.log("UPDATE LICENSE", username);
        new FileWorker("SAVE_LICENSES", null, null, licenses,
        () -> SwingUtilities.invokeLater(() -> {
            progressBar.setVisible(true);
            progressBar.setIndeterminate(true);
            progressBar.setString("Saving...");
        }),
        () -> SwingUtilities.invokeLater(() -> {
            progressBar.setIndeterminate(false);
            progressBar.setValue(100);
            progressBar.setString("Saved");
            javax.swing.Timer timer = new javax.swing.Timer(1500, e -> progressBar.setVisible(false));
            timer.setRepeats(false);
            timer.start();
        })).execute(); 
        refreshTable();
        clearFields();
        //end update button
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int selectedRow = tblLicenses.getSelectedRow();
        
        if(selectedRow == -1){
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a license to delete.");
            return;
        }//end if
        int choice = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this "
                + "license?","Confirm delete",javax.swing.JOptionPane.YES_NO_OPTION);
  
        if(choice != javax.swing.JOptionPane.YES_OPTION){
            return;
        }//end if
        
        CloudLicense licenseToDelete = licenses.get(selectedRow);
        LoggerUtil.log("DELETE LICENSE", username);
        
        licenses.remove(selectedRow);
        
        new FileWorker("SAVE_LICENSES", null, null, licenses,
        () -> SwingUtilities.invokeLater(() -> {
            progressBar.setVisible(true);
            progressBar.setIndeterminate(true);
            progressBar.setString("Saving...");
        }),
        () -> SwingUtilities.invokeLater(() -> {
            progressBar.setIndeterminate(false);
            progressBar.setValue(100);
            progressBar.setString("Saved");
            javax.swing.Timer timer = new javax.swing.Timer(1500, e -> progressBar.setVisible(false));
            timer.setRepeats(false);
            timer.start();
        })).execute();
        refreshTable();
        clearFields();
        //end delete button
    }//GEN-LAST:event_btnDeleteActionPerformed

