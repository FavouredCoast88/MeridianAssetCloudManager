    private void setupTable(){
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("License ID");
        model.addColumn("License Name");
        model.addColumn("License Count");
        model.addColumn("Monthly Cost");
        tblLicenses.setModel(model);
    }//end setupTable method
    
    private void refreshTable(){
        DefaultTableModel model = (DefaultTableModel) tblLicenses.getModel();
        model.setRowCount(0);
        
        for(CloudLicense license : licenses){
            model.addRow(new Object[]{
                license.getAssetId(), license.getAssetName(), license.getLicenseCount(),
                license.getMonthlyCost()});
        }//end for
    }//end refreshTable method
    
