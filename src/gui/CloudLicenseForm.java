    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String id = txtLicenseID.getText().trim();//Trim is used to allow spaces between words
        String name = txtLicenseName.getText().trim();
        String countText = txtLicenseCount.getText().trim();
        String costText = txtMonthlyCost.getText().trim();
        
        if(id.isEmpty()||name.isEmpty()||countText.isEmpty()||costText.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Please complete all fields!");
            return;
        }//end if
        
        int licenseCount;
        double monthlyCost;
        
        try{
            licenseCount = Integer.parseInt(countText);
            monthlyCost = Double.parseDouble(costText);
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "License count must be a whole number and "
                    + "montly cost must be a valid number.");
            return;
        }//end catch

        if(licenseCount < 0){
            JOptionPane.showMessageDialog(this, "License count cannot be negative.");
            return;   
        }//end if

        if(monthlyCost < 0){
            JOptionPane.showMessageDialog(this, "Monthly cost cannot be negative.");
            return;
        }//end if
        
        //Check for duplicate License IDs
        for(CloudLicense license : licenses){
            if(license.getAssetId().equalsIgnoreCase(id)){
                JOptionPane.showMessageDialog(this, "License ID already exists.");
                return;
            }//end if
        }//end for
        CloudLicense license = new CloudLicense(id, name, licenseCount, monthlyCost);
        licenses.add(license);
        LoggerUtil.log("ADD LICENSE", username);
        new FileWorker("SAVE_LICENSES", null, null, licenses,
        () -> SwingUtilities.invokeLater(() -> {
            progressBar.setVisible(true);
            progressBar.setIndeterminate(true);
            progressBar.setString("Saving...");
        }),
        () -> SwingUtilities.invokeLater(() -> {
            progressBar.setIndeterminate(false);
            progressBar.setValue(100);
            progressBar.setString("Saved");
            javax.swing.Timer timer = new javax.swing.Timer(1500, e -> progressBar.setVisible(false));
            timer.setRepeats(false);
            timer.start();
        })).execute(); 
        refreshTable();
        clearFields();
     //end add button
    }//GEN-LAST:event_btnAddActionPerformed

