    private void setupTable(){
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("Deployment ID");
        model.addColumn("Hardware ID");
        model.addColumn("License ID");
        tblDeploymentQueue.setModel(model);
    }//end sutupTable method
    
    private void loadQueue(){
        try{
            applicationState = Serializer.loadState();
            deploymentQueue = applicationState.getDeploymentQueue();
            licenses = FileManager.loadLicenses();
            hardwareList = FileManager.loadHardware();
            refreshTable();
        }catch(IOException | ClassNotFoundException e){
            applicationState = new ApplicationState();
            deploymentQueue = applicationState.getDeploymentQueue();
            licenses = new ArrayList<>();
            hardwareList = new LinkedList<>();
            JOptionPane.showMessageDialog(this, "Could not load deployment data.");
        }//end catch
    }//end loadQueue method
    
    private void refreshTable(){
        DefaultTableModel model = (DefaultTableModel) tblDeploymentQueue.getModel();
        model.setRowCount(0);

        for(String request : deploymentQueue){
            String[] data = request.split("\\|");
           
            if(data.length == 3){
               model.addRow(new Object[]{data[0], data[1], data[2]});
            }//end if
        }//end for
    }//end refreshTable method
    
    private void saveQueue(){
        try{
            applicationState.setDeploymentQueue(deploymentQueue);
            Serializer.saveState(applicationState);
        }catch(IOException e){
            JOptionPane.showMessageDialog(this, "Could not save deployment queue.");
        }//end catch
    }//end saveQueue method
    
    private void clearFields(){
        txtDeploymentID.setText("");
        txtDeploymentHardwareID.setText("");
        txtDeploymentLicenseID.setText("");
        txtDeploymentID.requestFocus();
    }//end clearFields method
    
    private CloudLicense findLicense(String licenseID) {
        for(CloudLicense license : licenses){    
            if(license.getAssetId().equalsIgnoreCase(licenseID)){
                return license;
            }//end if
        }//end for
        return null;
    }//end findLicense method
    
    private Hardware findHardware(String hardwareID){
        for(Hardware hardware : hardwareList){
            if(hardware.getAssetId().equalsIgnoreCase(hardwareID)){
                return hardware;
            }//end if
        }//end for
        return null;
    }//end findHardware method
    
    private void checkLicenseAvailability(CloudLicense license) throws InsufficientLicenseException{
        if(license.getLicenseCount() <= 0){
           throw new InsufficientLicenseException("No licenses are available for " 
                   + license.getAssetName() + ".");
        }//end if
    }//end checkLicenseAvailability method

