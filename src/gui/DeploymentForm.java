    private void btnProcessNextActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessNextActionPerformed
        if(deploymentQueue.isEmpty()){
            JOptionPane.showMessageDialog(this, "There are no deployments in the queue.");
            return;
        }//end if
        
        String request = deploymentQueue.peek();
        String[] data = request.split("\\|");
        if(data.length != 3){
            JOptionPane.showMessageDialog(this, "Invalid deployment request.");
            return;
        }//end if
       
        String deploymentID = data[0];
        String hardwareID = data[1];
        String licenseID = data[2];
       
        try{
            CloudLicense selectedLicense = findLicense(licenseID);
            Hardware selectedHardware = findHardware(hardwareID);
            if(selectedLicense == null){
                throw new InsufficientLicenseException("License " + licenseID + " could not be found.");
            }//end if

            if(selectedHardware == null){
                JOptionPane.showMessageDialog(this, "Hardware " + hardwareID 
                        + " could not be found.");
                return;
            }//end if

            // Check licence availability
            checkLicenseAvailability(selectedLicense);

            // Consume one licence
            selectedLicense.setLicenseCount(selectedLicense.getLicenseCount() - 1);

            // Assign the hardware
            selectedHardware.setStatus("Assigned");

            // Remove the request only after successful deployment
            deploymentQueue.poll();

            // Save everything
            FileManager.saveLicenses(licenses);
            FileManager.saveHardware(hardwareList);
            saveQueue();

            // Log successful deployment
            LoggerUtil.log("PROCESS DEPLOYMENT", username);
            refreshTable();
            JOptionPane.showMessageDialog(
                    this,
                    "Deployment completed successfully.\n\n"
                    + "Deployment: " + deploymentID
                    + "\nHardware: " + hardwareID
                    + "\nLicense: " + licenseID);
        }catch(InsufficientLicenseException e){
            LoggerUtil.log("FAILED DEPLOYMENT", username + " - " + e.getMessage());
            JOptionPane.showMessageDialog(this, e.getMessage(), "Deployment Failed"
                    , JOptionPane.WARNING_MESSAGE);
        }catch(IOException e){
            JOptionPane.showMessageDialog(this, "Could not save deployment data.");
        }//end catch       
     //end process next button
    }//GEN-LAST:event_btnProcessNextActionPerformed

