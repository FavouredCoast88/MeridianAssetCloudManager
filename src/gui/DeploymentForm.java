    private void btnAddToQueueActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddToQueueActionPerformed
        
        String deploymentID = txtDeploymentID.getText().trim();
        String hardwareID = txtDeploymentHardwareID.getText().trim();
        String licenseID = txtDeploymentLicenseID.getText().trim();
        
        if(deploymentID.isEmpty()|| hardwareID.isEmpty()|| licenseID.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please complete all deployment fields.");
            return;
        }//end if
        
        String request = deploymentID + "|" + hardwareID + "|" + licenseID;
        deploymentQueue.offer(request);
        saveQueue();
        refreshTable();
        LoggerUtil.log("ADD DEPLOYMENT", username);
        clearFields();
        JOptionPane.showMessageDialog(this, "Deployment added to the queue.");
     //end addToQueue button
    }//GEN-LAST:event_btnAddToQueueActionPerformed

